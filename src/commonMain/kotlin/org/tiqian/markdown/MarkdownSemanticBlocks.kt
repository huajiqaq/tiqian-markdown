package org.tiqian.markdown

/** Shared structural roles, not parser types. Source types and all fields live in metadata. */
enum class MarkdownContainerKind {
    DefinitionList,
    DefinitionTerm,
    DefinitionDescription,
    Admonition,
    Custom,
    Columns,
    Column,
    Tabs,
    Tab,
    Unknown,
}

data class MarkdownContainerBlock(
    val kind: MarkdownContainerKind,
    val blocks: List<MarkdownBlock>,
    override val metadata: MarkdownNodeMetadata,
    val title: MarkdownText? = null,
    val width: String? = null,
) : MarkdownBlock

data class MarkdownBibliographyEntry(
    val key: String,
    val text: MarkdownText,
    /** An entry may be generated by its parser; do not invent parser persistent IDs. */
    val metadata: MarkdownNodeMetadata,
)

data class MarkdownBibliographyBlock(
    val entries: List<MarkdownBibliographyEntry>,
    override val metadata: MarkdownNodeMetadata,
    val title: String = "References",
) : MarkdownBlock

data class MarkdownTocBlock(
    override val metadata: MarkdownNodeMetadata,
    val minDepth: Int = 1,
    val maxDepth: Int = 6,
    val excludedIds: List<String> = emptyList(),
    val reversed: Boolean = false,
) : MarkdownBlock

/** Diagram source is selectable code; diagram execution and remote rendering are host-owned. */
data class MarkdownDiagramBlock(
    val language: String,
    val source: String,
    override val metadata: MarkdownNodeMetadata,
) : MarkdownBlock

/** Screen presentation is a separator; print hosts may replace it with an actual page boundary. */
data class MarkdownPageBreakBlock(
    override val metadata: MarkdownNodeMetadata,
) : MarkdownBlock

/** One reading-order traversal shared by galleries, navigation, selection and prelayout. */
internal fun MarkdownBlock.childBlocks(): List<MarkdownBlock> = when (this) {
    is MarkdownBlockQuote -> blocks
    is MarkdownList -> items.flatMap { it.blocks }
    is MarkdownFootnoteDefinition -> blocks
    is MarkdownContainerBlock -> blocks
    is MarkdownCustomBlock -> blocks
    else -> emptyList()
}
